"""Step 4. Per-game building blocks so the Overview tab can re-grade any date range.

For every pitcher and game day: pitch count and summed model values by pitch type and batter side. A grade over a
date range is the same formula as the season grade (02_train_and_grade.py) applied to the days in the range, so the
whole season reproduces the season grade exactly.
Input: all.parquet, scored_final.parquet, grades.json (steps 1-3).
Output: ../../frontend/src/gradesDaily/<season>_<bucket>.js (16 lazy chunks per season) and gradesDailyConst.js
"""
import json, os, numpy as np, pandas as pd
OUT=os.environ.get('OUT_DIR','../../frontend/src/gradesDaily'); NB=16; SC=1e7
a=pd.read_parquet('all.parquet',columns=['gd','reg','pitcher_id']); a=a[a.reg].reset_index(drop=True)
D=pd.read_parquet('scored_final.parquet'); assert len(a)==len(D) and (a.pitcher_id.values==D.pitcher_id.values).all()
D['gd']=a.gd.astype(str).str[:10].values; D['res']=D.rv-D.pj
PTS=10/0.45; M=(('s','st'),('l','loc_val'),('p','pit'))
def kconst(col,keys,minn=60):
    g=D.groupby(keys)[col].agg(['size','mean','var']); g=g[g['size']>=minn]; sw=np.average(g['var'],weights=g['size']-1); sb=g['mean'].var()-np.mean(sw/g['size']); return max(sw/sb,1.0)
LV=(('all',['pitcher_id','season']),('side',['pitcher_id','season','stand']),('type',['pitcher_id','season','pitch_type']),('typeside',['pitcher_id','season','pitch_type','stand']))
KC={m:{lvl:float(kconst(col,keys)) for lvl,keys in LV} for m,col in M}
gq=D.groupby(['pitcher_id','season']).res.agg(['size','mean','var']); gq=gq[gq['size']>=60]; sw=np.average(gq['var'],weights=gq['size']-1); KGAP=float(sw/(gq['mean'].var()-np.mean(sw/gq['size'])))
G=json.load(open('grades.json'))['grades']; TYPES=sorted(D.pitch_type.dropna().unique()); const={'K':KC,'KGAP':KGAP,'PTS':PTS,'SC':SC,'TYPES':TYPES,'NB':NB,'MIN':25,'GAP':[4,8],'S':{}}
os.makedirs(OUT,exist_ok=True)
for y in (2025,2026):
    X=D[D.season==y]; day0=X.gd.min(); const['S'][str(y)]={'mu':[float(X[c].mean()) for _,c in M],'mrv':float(X.rv.mean()),'day0':day0,'tmu':{pt:[float(v) for v in r] for pt,r in X.groupby('pitch_type')[['st','loc_val','pit']].mean().iterrows()}}
    X=X[X.pitcher_id.astype(int).astype(str).isin(G[str(y)])]
    c=X.groupby(['pitcher_id','gd','pitch_type','stand']).agg(n=('st','size'),st=('st','sum'),lo=('loc_val','sum'),pi=('pit','sum'),re=('res','sum'),rv=('rv','sum')).reset_index()
    c['day']=(pd.to_datetime(c.gd)-pd.to_datetime(day0)).dt.days; c['ti']=c.pitch_type.map({t:i for i,t in enumerate(TYPES)}); c['sd']=(c.stand=='R').astype(int)
    for k in ('st','lo','pi','re','rv'): c[k]=np.round(c[k]*SC).astype(int)
    tot=0
    for b in range(NB):
        o={}
        for p,g in c[c.pitcher_id.astype(int)%NB==b].groupby('pitcher_id'):
            o[str(int(p))]=[v for r in g[['day','ti','sd','n','st','lo','pi','re','rv']].itertuples(index=False) for v in r]      # flat: 9 numbers per cell
        js="// Generated by tools/pitch-grades/04_daily.py. Per pitcher, flat cells of 9 numbers:\n// day (since the season's first game), pitch type index, batter side (0 L, 1 R), pitches, then summed Stuff / Location / Pitching model values,\n// results minus expectation and run value (runs x 1e7). See gradesDailyConst.js for the constants that turn sums into grades.\nexport default %s;\n"%json.dumps(o,separators=(',',':'))
        open(f'{OUT}/{y}_{b:02d}.js','w').write(js); tot+=len(js)
    print(y,'cells',len(c),'bytes',tot,flush=True)
open(os.path.join(os.path.dirname(OUT),'gradesDailyConst.js'),'w').write("// Generated by tools/pitch-grades/04_daily.py: constants for re-grading a date range from the per-game cells in gradesDaily/.\n// K = sample-size regression constants (pitches) by grade and level, KGAP the same for results vs grades, S[season] = league means.\nexport const GD = %s;\n"%json.dumps(const,separators=(',',':')))
print('K',{m:{k:round(v,1) for k,v in d.items()} for m,d in KC.items()},'KGAP',round(KGAP))
# --- check: the whole season, rebuilt from the cells, equals the season grades ---
def grade(sub,lvl,base,mu):
    n=sub.n.sum()
    if n<25: return None
    return [int(round(100-PTS*100*((((sub[k].sum()/SC/n)-base[i])*n/(n+KC[m][lvl])+base[i])-mu[i]))) for i,(m,k) in enumerate((('s','st'),('l','lo'),('p','pi')))]+[int(n)]
import glob,re
for y in (2025,2026):
    S=const['S'][str(y)]; bad=0; tot=0
    for f in sorted(glob.glob(f'{OUT}/{y}_*.js')):
        o=json.loads(re.search(r'export default (\{.*\});',open(f).read(),re.S).group(1))
        for p,flat in o.items():
            g=pd.DataFrame(np.array(flat).reshape(-1,9),columns=['day','ti','sd','n','st','lo','pi','re','rv']); e=G[str(y)][p]; tot+=1
            ok=grade(g,'all',S['mu'],S['mu'])==e['a'] and grade(g[g.sd==0],'side',S['mu'],S['mu'])==e['L'] and grade(g[g.sd==1],'side',S['mu'],S['mu'])==e['R']
            for pt,cells in e['t'].items():
                gt=g[g.ti==TYPES.index(pt)]; b=S['tmu'][pt]; ok=ok and grade(gt,'type',b,S['mu'])==cells[0] and grade(gt[gt.sd==0],'typeside',b,S['mu'])==cells[1] and grade(gt[gt.sd==1],'typeside',b,S['mu'])==cells[2]
            n=g.n.sum(); gap=-(g.re.sum()/SC/n)*100*PTS*n/(n+KGAP); lvl=int(np.sign(gap))*(2 if abs(gap)>=8 else 1 if abs(gap)>=4 else 0)
            if 'r' in e: ok=ok and [lvl,int(round(gap)),int(round(100-PTS*100*(g.rv.sum()/SC/n-S['mrv'])))]==e['r']
            bad+=(not ok)
    print(y,'pitchers',tot,'season grades not reproduced exactly:',bad)
